 local_mocked_bindings(.sc_act_root=.sc_act_root,.package='scAgentKit')
 scopes<-annot_act_scopes('human');expect_true('Blood' %in% scopes$tissue);expect_true(all(scopes$source_rows>0))
 human<-annot_act_reference('human',' Blood ');mouse<-annot_act_reference('mouse','blood')
 expect_equal(nrow(human),2021);expect_equal(nrow(mouse),158)
 expect_true(all(human$species=='human'));expect_true(all(mouse$species=='mouse'))
 expect_true(all(tolower(human$tissue)=='blood'));expect_true(all(tolower(mouse$tissue)=='blood'))
 expect_equal(length(unique(human$cell_type)),137);expect_equal(length(unique(mouse$cell_type)),30)
 expect_identical(human$pmid,human$act_pmid_original)
 expect_identical(human$SourceFile,human$act_source_file_original)
 expect_identical(human$SourceURL,human$act_source_url_original)
 expect_true(all(startsWith(human$SourceURL,'http://xteam.xbio.top/ACT/download/Human/')))
 expect_identical(attr(human,'original_sha256'),'afbd2d956e910ecdeb4f606ead3e48d0fc9501d36b976506bd636572081590e0')
 expect_identical(attr(mouse,'original_sha256'),'b22e6d2c120dab02b68d2a2cf4a82b2561a9047a7227519c5172c88170923a61')
 expect_identical(attr(human,'retrieved_at'),'2026-10-20');expect_true(is.na(attr(human,'source_date')))
 expect_false(attr(human,'source_url_verified'))
 expect_identical(attr(human,'act_citation')$doi,'10.1186/s13073-023-01249-5')
 empty<-annot_act_reference('mouse','__no_such_tissue__')
 expect_equal(nrow(empty),0);expect_identical(attr(empty,'scope_status'),'zero_matches')
 expect_match(attr(empty,'scope_notice'),'No broader tissue or cross-species fallback')
 expect_error(annot_act_reference('human','all'),'actual ACT tissue')
 expect_error(annot_act_reference('fish','Blood'),'species')
})

test_that('ACT manifest and either species asset cannot be silently substituted',{
 original<-.sc_act_root();copy<-tempfile();dir.create(copy);on.exit(unlink(copy,recursive=TRUE))
 file.copy(list.files(original,full.names=TRUE),copy)
 local_mocked_bindings(.sc_act_root=function()copy,.package='scAgentKit')
 asset<-file.path(copy,'ACT_Mouse_merged.tsv.gz');writeBin(charToRaw('changed'),asset)
 expect_error(annot_act_reference('human','Blood'),'asset changed')
 file.copy(file.path(original,'ACT_Mouse_merged.tsv.gz'),asset,overwrite=TRUE)
 cat(' ',file=file.path(copy,'PROVENANCE.json'),append=TRUE)
 expect_error(annot_act_reference('human','Blood'),'provenance changed')
})

test_that('new modern projects snapshot the bundled default; explicit reference and opt-out win',{
 e<-new.env();utils::data('pbmc_small',package='SeuratObject',envir=e)
 create<-function(root,...)sc_analyze(e$pbmc_small,root,context=list(species='human',tissue='blood'),provider='manual',
  qc_mad=FALSE,cycle_diagnostics=FALSE,doublet='off',plan=list(analysis=list(nfeatures=100,npcs=6),pcs=4,diagnostic_resolutions=c(.4,.6),umap=FALSE),...)
 root<-tempfile();on.exit(unlink(root,recursive=TRUE),add=TRUE);create(root)
 state<-.sc_run_load(root);ref<-.sc_run_get(root,state,'reference')
 expect_equal(nrow(ref),2021);expect_length(state$approvals,0)
 expect_match(state$config$reference_review$provenance$preparation_note,'ACT snapshot downloaded 2026-10-20')
 before<-.sc_project_sha_file(file.path(root,state$files$reference$path))
 expect_silent(sc_open(root));expect_identical(.sc_project_sha_file(file.path(root,state$files$reference$path)),before)
 off<-tempfile();on.exit(unlink(off,recursive=TRUE),add=TRUE);create(off,reference=NULL)
 expect_null(.sc_run_load(off)$files$reference)
 custom<-data.frame(species='human',tissue='blood',cell_type='Explicit custom',marker='CD3D')
 own<-tempfile();on.exit(unlink(own,recursive=TRUE),add=TRUE);create(own,reference=custom)
 expect_identical(.sc_run_get(own,.sc_run_load(own),'reference'),custom)
 expect_message(.sc_ui_act_default(list(species='human',tissue='__no_such_tissue__')),'no exact match')
})

test_that('ACT provenance records explicit unknowns rather than inferring website rights from the article', {
 manifest <- .sc_act_manifest()
 for (key in c('source_page','downloaded_date_as_supplied','publisher_release',
               'publisher_release_date','license_terms','license_url')) {
  expect_type(manifest[[key]], 'character')
  expect_length(manifest[[key]], 1L)
  expect_true(nzchar(trimws(manifest[[key]])))
 }
 expect_identical(manifest$publisher_release, 'unknown')
 expect_identical(manifest$license_terms, 'unknown')
 expect_match(manifest$provenance_review$license_scope_limit, 'has not been established')
 expect_identical(attr(annot_act_reference('human','blood'),'license'), 'unknown')
})
