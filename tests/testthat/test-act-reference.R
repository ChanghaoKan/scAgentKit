act_write_fixture <- function(table) {
  path<-tempfile(fileext=".tsv")
  utils::write.table(table,path,sep="\t",quote=TRUE,row.names=FALSE,na="")
  path
}
test_that("ACT local import records actual source bytes and original PMID strings without publisher authentication", {
  raw<-data.frame(Species=c("Homo sapiens","Human","Mouse","Human"),Tissue=c("Peripheral blood","Peripheral blood","blood","liver"),
    Cell=c("T cell","T cell","Mouse cell","Liver cell"),Gene=c("CD3D","CD3D","Cd3d","ALB"),PMID=c("PMID:12345","67890;13579","24680",""))
  path<-act_write_fixture(raw);on.exit(unlink(path))
  mapping<-c(species="Species",tissue="Tissue",cell_type="Cell",marker="Gene",pmid="PMID")
  ref<-annot_import_act(path,"human","blood",columns=mapping,source_version="synthetic-test-version",source_date="2026-10-19")
  expect_identical(ref$pmid,raw$PMID[1:2]);expect_identical(ref$act_pmid_original,raw$PMID[1:2])
  expect_identical(ref$source_row,2:3);expect_true(all(ref$source=="ACT"))
  expect_identical(attr(ref,"reference_source"),"ACT")
  expect_identical(attr(ref,"source_sha256"),digest::digest(file=path,algo="sha256"))
  expect_false(attr(ref,"source_url_verified"));expect_true(is.na(attr(ref,"source_url")))
  expect_identical(attr(ref,"source_version"),"synthetic-test-version")
  expect_identical(attr(ref,"source_date"),"2026-10-19")
  expect_identical(attr(ref,"license"),"unknown-not-verified-for-redistribution")
  expect_error(annot_import_act(path,"human","blood"),"actual header")
  expect_error(annot_import_act(path,"human","blood",columns=mapping,sha256=paste(rep("0",64),collapse="")),"SHA256 does not match")
  expect_error(annot_import_act(path,"human","all",columns=mapping),"actual ACT tissue")
  expect_error(annot_import_act(),"default ACT reference is unavailable")
  none<-annot_import_act(path,"human","heart",columns=mapping)
  expect_equal(nrow(none),0L);expect_identical(attr(none,"scope_status"),"zero_matches")
  expect_match(attr(none,"scope_notice"),"no all-tissue fallback")
})

test_that("ACT publication rows survive unique-marker coverage and conditional enrichment", {
  env<-new.env();utils::data("pbmc_small",package="SeuratObject",envir=env)
  seu<-env$pbmc_small;seu$seurat_clusters<-as.character(SeuratObject::Idents(seu))
  gene<-rownames(seu)[[1L]]
  raw<-data.frame(species="human",tissue="blood",cell_type="Synthetic ACT candidate",marker=gene,pmid=c("12345","67890"))
  path<-act_write_fixture(raw);on.exit(unlink(path))
  ref<-annot_import_act(path,"human","blood")
  expect_identical(attr(ref,"source_version"),"unversioned-user-local-input")
  expect_true(is.na(attr(ref,"source_date")))
  markers<-data.frame(cluster="0",gene=gene)
  attr(markers,"tested_background")<-list("0"=rownames(seu))
  out<-.sc_run_reference_evidence(seu,markers,list(species="human",tissue="blood"),ref,"seurat_clusters",list(strict_scope=TRUE))
  expect_identical(out$provenance$reference_source,"ACT")
  expect_identical(out$provenance$default_reference$source,"ACT")
  expect_equal(out$provenance$n_unique_pairs,1L)
  row<-Filter(function(row)row$clusterId=="0",out$per_cluster)[[1L]]$candidates[[1L]]
  expect_equal(row$score,1);expect_equal(row$overlap,1);expect_equal(row$referenceSize,1)
  expect_identical(vapply(row$publications,`[[`,"","pmid"),c("12345","67890"))
  expect_identical(row$reference_source,"ACT")
  expect_identical(row$enrichment[[1L]]$status,"tested")
  missing<-.sc_run_reference_evidence(seu,markers,list(species="human",tissue="blood"),NULL,"seurat_clusters",list(strict_scope=TRUE))
  expect_identical(missing$provenance$status,"not_supplied")
  expect_identical(missing$provenance$default_reference$source,"ACT")
  expect_identical(missing$provenance$default_reference$status,"unavailable_no_verified_local_file")
  expect_match(missing$provenance$scope_notice,"Default ACT reference unavailable")
})
