test_that("sc_start mock defaults traverse three human gates and replay without an API", {
  skip_if(Sys.which("python3") == "", "Python 3 is required for local startup")
  source(system.file("examples", "react-three-gate-mock.R", package = "scAgentKit"), local = TRUE)
  folder <- tempfile("start-e2e-"); dir.create(folder)
  on.exit(unlink(folder, recursive = TRUE))
  withr::local_envvar(c(DEEPSEEK_API_KEY = "", XAI_API_KEY = ""))
  result <- suppressWarnings(react_three_gate_mock(file.path(folder, "project"), file.path(folder, "input.rds")))
  state <- .sc_run_load(file.path(folder, "project"))
  expect_identical(state$status, "complete")
  expect_identical(state$config$react$mode, "all")
  expect_false(any(c("cost_mode", "budget") %in% names(state$config)))
  expect_true(state$config$biological_diagnostics$diagnostic_only)
  expect_length(state$approvals, 3L)
  expect_true(result$replay$matches)
  run <- .sc_run_get(file.path(folder, "project"), state, "annotation_react_run")
  expect_gt(run$tool_calls, 0L)
  expect_identical(run$status, "completed")
  expect_equal(result$receipt$real_api_calls, 0L)
  expect_length(result$receipt$proposal_hashes, 3L)
  expect_true(all(vapply(result$receipt$proposal_hashes, function(x) is.character(x) && length(x) == 1L && grepl("^[a-f0-9]{64}$", x), logical(1))))
})
