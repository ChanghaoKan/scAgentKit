test_that("bundled runtime matches R and detects missing, extra and modified assets", {
  runtime <- system.file("workbench",package="scAgentKit")
  expect_true(nzchar(runtime))
  expect_silent(scAgentKit:::.sc_start_runtime_check(runtime))
  copy <- tempfile("runtime-")
  dir.create(copy)
  on.exit(unlink(copy,recursive=TRUE),add=TRUE)
  expect_true(all(file.copy(list.files(runtime,full.names=TRUE,all.files=TRUE,no..=TRUE),copy,recursive=TRUE)))
  expect_silent(scAgentKit:::.sc_start_runtime_check(copy))
  target <- file.path(copy,"start_analysis.py")
  original <- readBin(target,"raw",n=file.info(target)$size)
  cat("\n# deliberate tamper\n",file=target,append=TRUE)
  expect_error(scAgentKit:::.sc_start_runtime_check(copy),"Runtime asset changed")
  writeBin(original,target)
  unlink(target)
  expect_error(scAgentKit:::.sc_start_runtime_check(copy),"asset inventory differs")
  writeBin(original,target)
  writeLines("unexpected",file.path(copy,"unexpected.py"))
  expect_error(scAgentKit:::.sc_start_runtime_check(copy),"asset inventory differs")
  unlink(file.path(copy,"unexpected.py"))
  dir.create(file.path(copy,"__pycache__"),showWarnings=FALSE)
  writeBin(as.raw(1),file.path(copy,"__pycache__","example.pyc"))
  expect_silent(scAgentKit:::.sc_start_runtime_check(copy))
  manifest_path <- file.path(copy,"runtime-manifest.json")
  manifest <- jsonlite::fromJSON(manifest_path,simplifyVector=FALSE)
  manifest$functions$sc_start <- paste(rep("0",64),collapse="")
  jsonlite::write_json(manifest,manifest_path,auto_unbox=TRUE)
  expect_error(scAgentKit:::.sc_start_runtime_check(copy),"Installed package and runtime differ")
})
